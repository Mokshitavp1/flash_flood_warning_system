import express from 'express';
import fs from 'node:fs/promises';
import path from 'node:path';

const app = express();
const root = process.cwd();
const outputs = path.join(root, 'outputs');
const port = Number(process.env.PORT ?? 8787);

function numberOrZero(value: unknown): number {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : 0;
}

async function readJson<T>(filePath: string, fallback: T): Promise<T> {
  try {
    return JSON.parse(await fs.readFile(filePath, 'utf8')) as T;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return fallback;
    throw error;
  }
}

async function pipelineData() {
  const stationsText = await fs.readFile(path.join(root, 'data', 'stations.csv'), 'utf8');
  const stationRows = stationsText.trim().split(/\r?\n/).slice(1).map((line) => line.split(','));
  const terrain = await readJson<Record<string, any>>(path.join(outputs, 'terrain', 'station_terrain.json'), {});
  const observations = new Map<string, { precipitation: number; temperature: number; pressure: number }>();
  for (const [id, row] of await Promise.all(stationRows.map(async ([id]) => {
    try {
      const text = await fs.readFile(path.join(root, 'data', `GHCNh_${id}_2025.psv`), 'utf8');
      const rows = text.trim().split(/\r?\n/);
      const headers = rows[0].split('|').map((header) => header.toLowerCase());
      const latest = rows.slice(1).at(-1)?.split('|');
      if (!latest) return [id, null] as const;
      const value = (names: string[]) => {
        const index = names.map((name) => headers.indexOf(name)).find((index) => index >= 0);
        return index === undefined ? 0 : numberOrZero(latest[index]);
      };
      return [id, {
        precipitation: value(['precipitation_1_hour', 'precipitation_1h']),
        temperature: value(['temperature']),
        pressure: value(['station_level_pressure']),
      }] as const;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [id, null] as const;
      throw error;
    }
  }))) {
    if (row) observations.set(id, row);
  }
  const stations = stationRows.map(([id, name, lat, lon, elevation]) => {
    const feature = terrain[id] ?? {};
    const observation = observations.get(id);
    return {
      id, name, lat: numberOrZero(lat), lon: numberOrZero(lon),
      elevationM: numberOrZero(feature.elevation_m ?? elevation),
      isElevated: Boolean(feature.is_elevated_terrain),
      slopeDeg: numberOrZero(feature.slope_degrees),
      aspectDeg: numberOrZero(feature.aspect_degrees),
      flowAccumCells: numberOrZero(feature.flow_accumulation_cells),
      currentPrecipMm: observation?.precipitation ?? 0,
      currentTempC: observation?.temperature ?? 0,
      currentPressureHpa: observation?.pressure ?? 0,
      status: observation?.precipitation && observation.precipitation >= 15
        ? 'storm' : feature.is_elevated_terrain ? 'storm' : 'normal',
    };
  });

  const manifestText = await fs.readFile(path.join(outputs, 'manifests', 'satellite_trajectory_manifest.csv'), 'utf8');
  const manifestRows = manifestText.trim().split(/\r?\n/).slice(1).map((line) => line.split(','));
  const trajectoryFrames = manifestRows.slice(0, 9).map((row) => ({
    offsetMin: numberOrZero(row[4]),
    targetTime: row[2],
    status: row[7] === 'ok' ? 'ok' : 'missing',
    matchedTime: row[5] || null,
    satelliteId: row[8] || 'NONE',
    irTempK: null,
    cloudFraction: row[10] ? numberOrZero(row[10]) : null,
    simulatedIntensity: 0,
  }));
  const alerts = await readJson<any[]>(path.join(outputs, 'alerts', 'alert_event_audit_log.json'), []);
  const evaluation = await readJson<Record<string, any>>(path.join(outputs, 'evaluation', 'ablation_benchmark_results.json'), {});
  const ablationScores = Object.entries(evaluation).map(([stageId, value]) => ({
    stageId,
    name: value.stage_name ?? stageId,
    csi: numberOrZero(value.metrics?.csi),
    pod: numberOrZero(value.metrics?.pod),
    far: numberOrZero(value.metrics?.far),
    f1: numberOrZero(value.metrics?.f1_score),
    description: value.description ?? value.notes ?? 'Generated by the Python pipeline.',
    isBaseline: stageId.startsWith('baseline'),
  }));
  return {
    generatedAt: new Date().toISOString(),
    source: 'HydroAlert pipeline outputs',
    stations, trajectoryFrames, alerts, ablationScores,
  };
}

app.get('/api/pipeline-data', async (_request, response) => {
  try {
    response.json(await pipelineData());
  } catch (error) {
    response.status(500).send(error instanceof Error ? error.message : 'Failed to read pipeline outputs.');
  }
});

app.use(express.static(path.join(root, 'dist')));
app.listen(port, () => console.log(`HydroAlert frontend API listening on http://localhost:${port}`));
